BAK = '.bak-kpiating'; MAN = '.kpiating-manifesto.json'
def ler(p):
    t = open(p, 'rb').read().decode('utf-8'); return t, '\r\n' in t
def gravar(p, s, crlf):
    if crlf: s = s.replace('\r\n', '\n').replace('\n', '\r\n')
    open(p, 'wb').write(s.encode('utf-8'))
def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    os.chdir(os.path.abspath(args[0] if args else '.')); dry = '--dry-run' in sys.argv
    if not os.path.exists('lib/vendas/kpi-handlers.ts'): sys.exit('ERRO: rode na RAIZ do projeto (não achei lib/vendas/kpi-handlers.ts).')
    if '--desfazer' in sys.argv:
        if not os.path.exists(MAN): sys.exit('Nada a desfazer (manifesto não encontrado).')
        for p in json.load(open(MAN, encoding='utf-8'))['salvos']:
            if os.path.exists(p + BAK):
                print(('restauraria ' if dry else 'restaurando ') + p)
                if not dry: shutil.copy2(p + BAK, p); os.remove(p + BAK)
        if not dry: os.remove(MAN)
        print('(dry-run: nada foi alterado)' if dry else 'Pronto. Desfeito.'); return
    plano = []
    for p, hs in D['edits'].items():
        if not os.path.exists(p): sys.exit('RECUSEI: não achei ' + p)
        atual, crlf = ler(p); base = atual.replace('\r\n', '\n')
        if all(n in base for _, n in hs) and all(v not in base for v, n in hs if v != n and v not in n): plano.append((p, None, crlf, 'já aplicado')); continue
        for v, n in hs:
            if base.count(v) != 1: sys.exit('RECUSEI: trecho não encontrado (ou repetido) em ' + p + ':\n  ' + v.split('\n')[0][:120] + '\nNada foi alterado. Me mande o arquivo atual.')
            base = base.replace(v, n)
        plano.append((p, base, crlf, f'{len(hs)} trechos'))
    for p, novo in D['sobrescrever'].items():
        if os.path.exists(p) and ler(p)[0].replace('\r\n', '\n') == novo: plano.append((p, None, False, 'igual'))
        else: plano.append((p, novo, os.path.exists(p) and ler(p)[1], 'troca'))
    for p, _, _, a in plano: print(f'  {p}: {a}')
    if dry: print('(dry-run: nada foi alterado)'); return
    man = json.load(open(MAN, encoding='utf-8')) if os.path.exists(MAN) else {'salvos': []}
    for p, novo, crlf, _ in plano:
        if novo is None: continue
        if os.path.exists(p) and not os.path.exists(p + BAK): shutil.copy2(p, p + BAK)
        if p not in man['salvos']: man['salvos'].append(p)
        gravar(p, novo, crlf)
    json.dump(man, open(MAN, 'w', encoding='utf-8'), indent=1)
    print('Pronto. Teste: node tests/unit/rodar.mjs')
main()
