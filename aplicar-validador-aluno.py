SIDE = 'components/shell/Sidebar.tsx'; BAK = '.bak-validador'; MAN = '.validador-manifesto.json'

def ler(p):
    with open(p, 'rb') as f: b = f.read()
    return b.decode('utf-8'), ('\r\n' in b.decode('utf-8'))
def gravar(p, s, crlf):
    os.makedirs(os.path.dirname(p) or '.', exist_ok=True)
    if crlf: s = s.replace('\r\n', '\n').replace('\n', '\r\n')
    with open(p, 'wb') as f: f.write(s.encode('utf-8'))

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    raiz = os.path.abspath(args[0] if args else '.'); os.chdir(raiz)
    dry = '--dry-run' in sys.argv; desf = '--desfazer' in sys.argv
    if not os.path.exists(SIDE): sys.exit('ERRO: rode na RAIZ do projeto (não achei ' + SIDE + ').')

    if desf:
        if not os.path.exists(MAN): sys.exit('Nada a desfazer (manifesto não encontrado).')
        man = json.load(open(MAN, encoding='utf-8'))
        for p in man['criados']:
            if dry: print('apagaria', p); continue
            if os.path.exists(p): os.remove(p)
        for p in man['salvos']:
            if os.path.exists(p + BAK):
                print(('restauraria ' if dry else 'restaurando ') + p)
                if not dry: shutil.copy2(p + BAK, p); os.remove(p + BAK)
        if not dry: os.remove(MAN)
        print('Pronto. Desfeito.' if not dry else '(dry-run: nada foi alterado)'); return

    sidebar, crlf = ler(SIDE)
    ja = 'validador-aluno' in sidebar
    novo_side = sidebar
    if not ja:
        base = sidebar.replace('\r\n', '\n')
        for velho, novo in D['edits']:
            if base.count(velho) != 1: sys.exit('RECUSEI: não achei (ou achei mais de uma vez) este trecho em ' + SIDE + ':\n  ' + velho.split('\n')[0] + '\nNada foi alterado. Me mande o arquivo atual.')
            base = base.replace(velho, novo)
        novo_side = base
    plano = []
    for p, conteudo in D['novos'].items():
        if os.path.exists(p):
            atual, _ = ler(p)
            if atual.replace('\r\n', '\n') == conteudo: plano.append((p, 'igual')); continue
            plano.append((p, 'troca'))
        else: plano.append((p, 'novo'))
    for p, a in plano: print(f'  {p}: {a}')
    print(f'  {SIDE}: ' + ('já tinha o item (nada a fazer)' if ja else '2 edições'))
    if dry: print('(dry-run: nada foi alterado)'); return

    man = json.load(open(MAN, encoding='utf-8')) if os.path.exists(MAN) else {'criados': [], 'salvos': []}
    if not ja:
        if not os.path.exists(SIDE + BAK): shutil.copy2(SIDE, SIDE + BAK)
        gravar(SIDE, novo_side, crlf)
        if SIDE not in man['salvos']: man['salvos'].append(SIDE)
    for p, a in plano:
        if a == 'igual': continue
        if a == 'troca':
            if not os.path.exists(p + BAK): shutil.copy2(p, p + BAK)
            if p not in man['salvos']: man['salvos'].append(p)
        else:
            if p not in man['criados']: man['criados'].append(p)
        gravar(p, D['novos'][p], crlf)
    json.dump(man, open(MAN, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('Pronto. Teste: node tests/unit/rodar.mjs   e   abra Ferramentas > Validador de Tipo de Aluno.')

main()
