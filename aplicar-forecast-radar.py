BAK = '.bak-fcradar'; MAN = '.fcradar-manifesto.json'
def ler(p):
    t = open(p, 'rb').read().decode('utf-8'); return t, '\r\n' in t
def gravar(p, s, crlf):
    os.makedirs(os.path.dirname(p) or '.', exist_ok=True)
    if crlf: s = s.replace('\r\n', '\n').replace('\n', '\r\n')
    open(p, 'wb').write(s.encode('utf-8'))
def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    os.chdir(os.path.abspath(args[0] if args else '.')); dry = '--dry-run' in sys.argv
    if not os.path.exists('lib/dashboard/yoy.ts'): sys.exit('ERRO: rode na RAIZ do Comercial360 (não achei lib/dashboard/yoy.ts).')
    if '--desfazer' in sys.argv:
        if not os.path.exists(MAN): sys.exit('Nada a desfazer (manifesto não encontrado).')
        man = json.load(open(MAN, encoding='utf-8'))
        for p in man['criados']:
            print(('apagaria ' if dry else 'apagando ') + p)
            if not dry and os.path.exists(p):
                os.remove(p)
                try: os.removedirs(os.path.dirname(p))      # tira as pastas que ficaram vazias
                except OSError: pass
        for p in man['salvos']:
            if os.path.exists(p + BAK):
                print(('restauraria ' if dry else 'restaurando ') + p)
                if not dry: shutil.copy2(p + BAK, p); os.remove(p + BAK)
        if not dry: os.remove(MAN)
        print('(dry-run: nada foi alterado)' if dry else 'Pronto. Desfeito.'); return
    plano = []; FALHAS = []
    OPCIONAIS = set()      # só serve para instalar o banco do zero
    for p, hs in D['edits'].items():
        if not os.path.exists(p):
            if p in OPCIONAIS: print(f'  {p}: não existe aqui, pulei'); continue
            sys.exit('RECUSEI: não achei ' + p)
        atual, crlf = ler(p); base = atual.replace('\r\n', '\n')
        if p in OPCIONAIS and not (all(n in base for _, n in hs) or all(base.count(v) == 1 for v, _ in hs)):
            print(f'  {p}: diferente do esperado, pulei'); continue
        if all(n in base for _, n in hs) and all(base.count(v) == 0 for v, n in hs if v not in n):
            plano.append((p, None, crlf, 'edit', 'já aplicado')); continue
        for v, n in hs:
            if base.count(v) != 1: FALHAS.append((p, v.split('\n')[0][:120])); continue
            base = base.replace(v, n)
        plano.append((p, base, crlf, 'edit', f'{len(hs)} trechos'))
    if FALHAS:
        print('RECUSEI: estes trechos não foram encontrados (ou estão repetidos). Nada foi alterado:')
        for p, t in FALHAS: print('  ' + p + ' :: ' + t)
        print('Me mande os arquivos listados acima (só esses).'); sys.exit(1)
    for p, c in D['novos'].items():
        if os.path.exists(p):
            a, crlf = ler(p)
            if a.replace('\r\n', '\n') == c: plano.append((p, None, crlf, 'novo', 'igual')); continue
            plano.append((p, c, crlf, 'troca', 'troca (com cópia)'))
        else: plano.append((p, c, False, 'novo', 'novo'))
    for p, b64 in D.get('bin', {}).items():
        dados = base64.b64decode(b64)
        if os.path.exists(p):
            if open(p, 'rb').read() == dados: plano.append((p, None, False, 'bin', 'igual')); continue
            plano.append((p, dados, False, 'bin', 'troca (com cópia)'))
        else: plano.append((p, dados, False, 'bin', 'novo'))
    for p, _, _, _, a in plano: print(f'  {p}: {a}')
    if dry: print('(dry-run: nada foi alterado)'); return
    man = json.load(open(MAN, encoding='utf-8')) if os.path.exists(MAN) else {'criados': [], 'salvos': []}
    for p, novo, crlf, k, a in plano:
        if novo is None: continue
        if p in man['criados']: pass   # já era arquivo criado por uma aplicação anterior: o desfazer apaga
        elif os.path.exists(p):
            if not os.path.exists(p + BAK): shutil.copy2(p, p + BAK)
            if p not in man['salvos']: man['salvos'].append(p)
        else: man['criados'].append(p)
        if k == 'bin':
            os.makedirs(os.path.dirname(p) or '.', exist_ok=True); open(p, 'wb').write(novo)
        else: gravar(p, novo, crlf)
    json.dump(man, open(MAN, 'w', encoding='utf-8'), indent=1)
    print('Pronto. Falta: (1) rodar sql/migration-forecast-radar-meta.sql UMA vez no Supabase; (2) deploy.')
main()
